#!/bin/sh
# Game controller mappings for the IPK.
#
#   OUTPUT_FILE=<path> sh webos/gen_gamecontrollerdb.sh    write the file that gets packaged
#   sh webos/gen_gamecontrollerdb.sh update [<ref>]        refresh the snapshot from upstream
#
# Packaging reads webos/gamecontrollerdb.txt, a snapshot of the Linux section of
# https://github.com/mdqinc/SDL_GameControllerDB kept in this repository. A build therefore
# needs no network for it, always ships the same mappings, and cannot silently ship an empty
# file because a download failed.
#
# SDL only loads the mappings whose platform field equals SDL_GetPlatform(). The TV runs a
# Linux kernel, so the controller GUIDs are the Linux ones, but the name its SDL reports is
# "webOS" for a webOS-aware SDL and "Linux" for a stock one. Each mapping is written once
# per name; SDL skips the copy that does not apply.
set -eu

SNAPSHOT="$(dirname "$0")/gamecontrollerdb.txt"
UPSTREAM="https://raw.githubusercontent.com/mdqinc/SDL_GameControllerDB"

if [ "${1:-}" = "update" ]; then
  REF="${2:-master}"
  TMP="$(mktemp)"
  trap 'rm -f "$TMP"' EXIT
  curl -fsSL "${UPSTREAM}/${REF}/gamecontrollerdb.txt" -o "$TMP"
  {
    cat <<EOF
# Linux section of the SDL game controller database, unmodified apart from the selection.
# Source: ${UPSTREAM}/${REF}/gamecontrollerdb.txt
# Refresh with: sh webos/gen_gamecontrollerdb.sh update <commit>
#
# Copyright (C) 1997-2025 Sam Lantinga <slouken@libsdl.org>
#
# This software is provided 'as-is', without any express or implied
# warranty.  In no event will the authors be held liable for any damages
# arising from the use of this software.
#
# Permission is granted to anyone to use this software for any purpose,
# including commercial applications, and to alter it and redistribute it
# freely, subject to the following restrictions:
#
# 1. The origin of this software must not be misrepresented; you must not
#    claim that you wrote the original software. If you use this software
#    in a product, an acknowledgment in the product documentation would be
#    appreciated but is not required.
# 2. Altered source versions must be plainly marked as such, and must not be
#    misrepresented as being the original software.
# 3. This notice may not be removed or altered from any source distribution.

EOF
    grep ',platform:Linux,$' "$TMP"
  } > "$SNAPSHOT"
  echo "$(grep -c ',platform:Linux,$' "$SNAPSHOT") mappings written to $SNAPSHOT"
  exit 0
fi

: "${OUTPUT_FILE:?OUTPUT_FILE is not set}"
MAPPINGS="$(grep -c ',platform:Linux,$' "$SNAPSHOT" || true)"
[ "${MAPPINGS:-0}" -gt 0 ] || { echo "$SNAPSHOT has no Linux mappings" >&2; exit 1; }
{
  echo "# Generated by webos/gen_gamecontrollerdb.sh from webos/gamecontrollerdb.txt"
  sed -n 's/,platform:Linux,$/,platform:webOS,/p' "$SNAPSHOT"
  grep ',platform:Linux,$' "$SNAPSHOT"
} > "$OUTPUT_FILE"
echo "${OUTPUT_FILE}: ${MAPPINGS} mappings, each for platform webOS and Linux"
